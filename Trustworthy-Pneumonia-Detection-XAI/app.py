"""
Streamlit frontend for the trustworthy chest X-ray pneumonia demo.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ.setdefault("MPLBACKEND", "Agg")

PROJECT_ROOT = Path(__file__).resolve().parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import streamlit as st
import torch

from configs.config import MODEL_SAVE_DIR, MODEL_WEIGHTS_NAME, OUTPUT_DIR, ensure_dirs
from inference.api import predict

st.set_page_config(
    page_title="Trustworthy Pneumonia Detection",
    page_icon="🫁",
    layout="wide",
)

ensure_dirs()

st.markdown(
    """
    <style>
      .block-container {padding-top: 1.2rem; max-width: 1200px;}
      .trust-pill {padding: 0.35rem 0.8rem; border-radius: 999px; font-weight: 700; display: inline-block;}
    </style>
    """,
    unsafe_allow_html=True,
)


def checkpoint_path() -> Path:
    return MODEL_SAVE_DIR / MODEL_WEIGHTS_NAME


def trust_color(level: str) -> str:
    return {"High": "#2ecc71", "Medium": "#f39c12", "Low": "#e74c3c"}.get(level, "#95a5a6")


def show_png_grid(paths: list[Path], width: int = 900) -> None:
    if not paths:
        st.info("No figures yet. Train in Colab / CLI first, then generate the faculty report.")
        return
    for path in paths:
        st.subheader(path.stem.replace("_", " ").title())
        st.image(str(path), width=width)


def page_predict() -> None:
    st.header("Screen a chest X-ray")
    st.caption("Upload one image. The pipeline returns class, calibrated confidence, Grad-CAM, uncertainty, and TrustScore.")

    ckpt = checkpoint_path()
    if not ckpt.exists():
        st.error(
            f"No trained model at `{ckpt}`. Run training in the Colab notebook or "
            "`python -m training.train --quick` first."
        )
        return

    left, right = st.columns([1, 1.15])
    with left:
        uploaded = st.file_uploader("Chest X-ray (.jpg / .jpeg / .png)", type=["jpg", "jpeg", "png"])
        n_mc = st.slider("MC Dropout samples", min_value=8, max_value=30, value=16, step=2)
        run = st.button("Run trustworthy pipeline", type="primary", disabled=uploaded is None)

    if uploaded is not None:
        with left:
            st.image(uploaded, caption="Uploaded X-ray", use_container_width=True)

    if not run or uploaded is None:
        return

    upload_dir = OUTPUT_DIR / "uploads"
    upload_dir.mkdir(parents=True, exist_ok=True)
    image_path = upload_dir / uploaded.name
    image_path.write_bytes(uploaded.getvalue())

    with st.spinner("Running MC Dropout, temperature scaling, Grad-CAM, and TrustEngine..."):
        result = predict(str(image_path), n_mc_samples=n_mc)

    level = str(result["trust_level"])
    color = trust_color(level)

    with right:
        c1, c2, c3 = st.columns(3)
        c1.metric("Prediction", result["predicted_class"])
        c2.metric("Calibrated confidence", f"{result['calibrated_confidence']:.3f}")
        c3.metric("Trust score", f"{result['trust_score']:.3f}")

        st.markdown(
            f'<span class="trust-pill" style="background:{color}33;color:{color};">'
            f"Trust level: {level} &nbsp;|&nbsp; OOD flag: {result['ood_flag']}</span>",
            unsafe_allow_html=True,
        )
        st.write("")
        m1, m2, m3 = st.columns(3)
        m1.metric("Raw confidence", f"{result['raw_confidence']:.3f}")
        m2.metric("Uncertainty", f"{result['uncertainty_score']:.5f}")
        m3.metric("Focus score", f"{result['focus_score']:.3f}")

        overlay = result.get("overlay_path")
        if overlay and Path(overlay).exists():
            st.image(overlay, caption="Grad-CAM + MC Dropout + trust panel", use_container_width=True)


def page_faculty_graphs() -> None:
    st.header("Faculty figure pack")
    st.caption("These are the supporting graphs generated by `python -m evaluation.faculty_report`.")
    report = OUTPUT_DIR / "faculty_report"
    paths = sorted(report.glob("*.png"))
    if st.button("Generate / refresh faculty graphs"):
        import subprocess

        with st.spinner("Computing metrics, ROC, calibration, trust, and Grad-CAM gallery..."):
            code = subprocess.call(
                [
                    sys.executable,
                    "-m",
                    "evaluation.faculty_report",
                    "--max_samples",
                    "120",
                    "--n_trust",
                    "32",
                    "--n_mc",
                    "10",
                    "--n_gradcam",
                    "8",
                ],
                cwd=str(PROJECT_ROOT),
            )
        if code != 0:
            st.error("Figure generation failed. Train the model and prepare the test set first.")
        else:
            st.rerun()
    show_png_grid(paths)


def page_pipeline() -> None:
    st.header("Training and evaluation outputs")
    names = [
        "training_curves.png",
        "reliability_diagrams.png",
        "evaluation_results.png",
        "trustscore_distribution.png",
    ]
    found = [OUTPUT_DIR / name for name in names if (OUTPUT_DIR / name).exists()]
    extra = sorted(OUTPUT_DIR.glob("*_uncertainty_gradcam.png"))
    show_png_grid(found + extra)


def page_about() -> None:
    st.header("What this system shows")
    st.markdown(
        """
        This is a **research decision-support prototype**, not a clinical device.

        1. **Classifier** — ResNet18 (or other CNNs) predicts Normal vs Pneumonia.
        2. **Calibration** — Temperature scaling makes confidence scores honest.
        3. **Explainability** — Grad-CAM highlights the pixels that drove the decision.
        4. **FocusScore** — Checks whether that heatmap overlaps a lung-region prior.
        5. **Uncertainty** — Monte Carlo Dropout variance flags unstable answers.
        6. **TrustEngine** — Combines confidence, focus, uncertainty, and agreement:

        `TrustScore = Confidence × FocusScore × (1 − Uncertainty) × Agreement`
        """
    )


def main() -> None:
    st.title("Trustworthy Pneumonia Detection")
    st.markdown("Calibrated deep learning + Grad-CAM + uncertainty + TrustScore for chest X-rays.")

    device = "CUDA GPU" if torch.cuda.is_available() else "CPU"
    ckpt = checkpoint_path()
    with st.sidebar:
        st.subheader("System")
        st.write(f"**Device:** {device}")
        st.write(f"**Checkpoint:** {'ready' if ckpt.exists() else 'missing'}")
        st.write(f"**Outputs:** `{OUTPUT_DIR}`")
        st.markdown("---")
        st.markdown("Tabs match the Colab demo: predict, faculty graphs, pipeline plots.")

    predict_tab, graphs_tab, pipeline_tab, about_tab = st.tabs(
        ["Screen an X-ray", "Faculty graphs", "Pipeline results", "How it works"]
    )
    with predict_tab:
        page_predict()
    with graphs_tab:
        page_faculty_graphs()
    with pipeline_tab:
        page_pipeline()
    with about_tab:
        page_about()


if __name__ == "__main__":
    main()
